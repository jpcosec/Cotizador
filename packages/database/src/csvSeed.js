// ── Loader ──────────────────────────────────────────────────────────────────

const LOADERS = {
  // Block 1 — Reference data
  CLIENTES:        coerceCliente,
  PERFILES_PRECIO: coercePerfil,
  PERFILES_INICIALIZACION: coercePerfilInit,
  CATEGORIAS:      coerceCategoria,
  ITEM_CATALOGO:   coerceItem,
  COMPOSICION_KIT: coerceComposicion,
  REGLAS_NEGOCIO:  coerceRegla,
  // Block 2 — Transactional data
  COTIZACIONES:         coerceCotizacion,
  LINEA_DETALLE:        coerceLinea,
  AJUSTES_COTIZACION:   coerceAjuste,
  CACHE_COTIZACION:     coerceCache,
  HISTORIAL_COTIZACION: coerceHistorial,
};

function loadTable(dirPath, tableName, coerce) {
  const filePath = path.resolve(dirPath, `${tableName}.csv`);
  if (!fs.existsSync(filePath)) return [];
  const raw = parseCsv(fs.readFileSync(filePath, 'utf8'));
  return raw.map(coerce);
}

/**
 * Load all catalog + config tables from a directory of CSV files.
 * Returns an array in SEED_DATA format: [{ table, records }]
 *
 * @param {string} dirPath - path to directory containing CSV files
 * @param {string[]} [tables] - subset of tables to load (defaults to all supported)
 */
export function loadSeedFromCsvDir(dirPath, tables = Object.keys(LOADERS)) {
  return tables
    .filter(t => LOADERS[t])
    .map(table => ({
      table,
      records: loadTable(dirPath, table, LOADERS[table]),
    }))
    .filter(entry => entry.records.length > 0);
}
