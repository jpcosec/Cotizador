/**
 * csvSeed.js — Node.js-only utility for loading real CSV data into SEED_DATA format.
 *
 * Usage (Node.js / vitest only — not for browser):
 *
 *   import { loadSeedFromCsvDir } from './csvSeed.js';
 *   const seed = loadSeedFromCsvDir('./data/init');
 *   const db = createDatabase({ seed });
 *
 * The CSV files are expected to already use the exact field names from Config_Schema.js.
 *
 * Adjustments applied automatically:
 *   - REGLAS_NEGOCIO: adds ID_Componente: null (field absent from CSV)
 *   - REGLAS_NEGOCIO: Condicion_JSON / Payload_JSON parsed from JSON strings to objects
 *   - Boolean strings ('true'/'false') → actual booleans
 *   - Numeric fields → numbers (empty string → null)
 *   - Nullable FK fields (empty string → null)
 *
 * NOTE: The REGLAS_NEGOCIO conditions use `linea.ID_Item` / `linea._pax` variable paths
 * (generated by the V1 migration tool). The new Item domain uses `itemId` / `pax` paths.
 * When wiring rules to the new RulesCoordinator, update condition variable paths accordingly.
 */

import fs from 'node:fs';
import path from 'node:path';

// ── CSV parser ──────────────────────────────────────────────────────────────

function stripBom(s) {
  return s && s.charCodeAt(0) === 0xfeff ? s.slice(1) : s;
}

function parseCsvLine(line) {
  const cells = [];
  let cur = '';
  let inQ = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    const nx = line[i + 1];
    if (ch === '"') {
      if (inQ && nx === '"') { cur += '"'; i++; }
      else inQ = !inQ;
      continue;
    }
    if (ch === ',' && !inQ) { cells.push(cur); cur = ''; continue; }
    cur += ch;
  }
  cells.push(cur);
  return cells;
}

function parseCsv(content) {
  const lines = content.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n').filter(l => l.trim());
  if (!lines.length) return [];
  const headers = parseCsvLine(stripBom(lines[0])).map(h => h.trim());
  return lines.slice(1).map(line => {
    const vals = parseCsvLine(line);
    const row = {};
    headers.forEach((h, i) => { row[h] = vals[i] ?? ''; });
    return row;
  });
}

// ── Type coercion helpers ───────────────────────────────────────────────────

function toBool(v) {
  if (v === true || v === false) return v;
  return String(v).toLowerCase() === 'true';
}

function toNum(v) {
  if (v === '' || v == null) return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
}

function toNullable(v) {
  return v === '' || v == null ? null : v;
}

function toJson(v) {
  if (!v || v === '') return null;
  if (typeof v === 'object') return v;
  try { return JSON.parse(v); } catch { return v; }
}

